/* ---- running Python ---- */

struct job {
    const char *script;     /* file run as __main__ */
    int argc;
    char *argv[8];          /* sys.argv */
    bool renpy;             /* engine on sys.path */
    int rc;
    volatile bool done;
};

static int exit_code_of(PyObject *exc)
{
    PyObject *code = PyObject_GetAttrString(exc, "code");
    int rc = 1;
    if (code == Py_None)
        rc = 0;
    else if (code && PyLong_Check(code))
        rc = (int)PyLong_AsLong(code);
    Py_XDECREF(code);
    PyErr_Clear();
    return rc;
}

/* CPython checks stdout/stderr with fstat(), which libnx's console device does
 * not implement, so it leaves sys.stdout/sys.stderr as None and every print()
 * and traceback is silently dropped. Reattach them: to RSL_PYLOG (a file) if
 * set, otherwise to fds 1/2 (the console; FileIO tolerates the fstat error). */
static const char STDIO_SETUP[] =
    "import io, os, sys\n"
    "def _rsl_fd(fd):\n"
    "    return io.TextIOWrapper(io.FileIO(fd, 'w', closefd=False), encoding='utf-8',\n"
    "                            errors='backslashreplace', line_buffering=True)\n"
    "_rsl_log = os.environ.get('RSL_PYLOG')\n"
    "if _rsl_log:\n"
    "    sys.stdout = sys.stderr = open(_rsl_log, 'a', encoding='utf-8', errors='backslashreplace', buffering=1)\n"
    "else:\n"
    "    if sys.stdout is None: sys.stdout = _rsl_fd(1)\n"
    "    if sys.stderr is None: sys.stderr = _rsl_fd(2)\n"
    "del _rsl_fd, _rsl_log\n";

/* Returns the script's exit status, or -1 if Python itself failed. */
static int run_python(struct job *j)
{
    PyPreConfig pre;
    PyPreConfig_InitIsolatedConfig(&pre);
    pre.utf8_mode = 1;             /* as Ren'Py's own launchers do */
    PyStatus st = Py_PreInitialize(&pre);

    PyConfig c;
    PyConfig_InitIsolatedConfig(&c);
    c.site_import = 0;
    c.write_bytecode = 0;
    c.buffered_stdio = 0;
    c.install_signal_handlers = 0;
    c.parse_argv = 0;
    c.module_search_paths_set = 1;
    if (!PyStatus_Exception(st) && j->renpy)
        st = PyWideStringList_Append(&c.module_search_paths, L"" RENPY_BASE);
    if (!PyStatus_Exception(st))
        st = PyWideStringList_Append(&c.module_search_paths, STDLIB_ZIP);
    if (!PyStatus_Exception(st))
        st = PyConfig_SetString(&c, &c.home, L"romfs:/lib");
    if (!PyStatus_Exception(st))
        st = PyConfig_SetBytesArgv(&c, j->argc, j->argv);
    if (!PyStatus_Exception(st))
        st = Py_InitializeFromConfig(&c);
    PyConfig_Clear(&c);
    if (PyStatus_Exception(st)) {
        rsl_log("Python init failed: %s: %s", st.func ? st.func : "?", st.err_msg ? st.err_msg : "?");
        printf("Python init failed: %s: %s\n", st.func ? st.func : "?", st.err_msg ? st.err_msg : "?");
        return -1;
    }
    rsl_log("Python %s initialised", Py_GetVersion());
    g_interp = PyInterpreterState_Get();
    if (PyRun_SimpleString(STDIO_SETUP) != 0)
        rsl_log("could not attach Python stdout/stderr");

    int rc = 0;
    FILE *f = fopen(j->script, "rb");
    if (!f) {
        rsl_log("cannot open %s", j->script);
        printf("cannot open %s\n", j->script);
        rc = -1;
    } else {
        PyObject *globals = PyModule_GetDict(PyImport_AddModule("__main__"));
        PyObject *file = PyUnicode_FromString(j->script);
        PyDict_SetItemString(globals, "__file__", file);
        Py_XDECREF(file);
        PyObject *r = PyRun_FileExFlags(f, j->script, Py_file_input, globals, globals, 1, NULL);
        if (r) {
            Py_DECREF(r);
        } else if (PyErr_ExceptionMatches(PyExc_SystemExit)) {
            /* PyErr_Print would call exit() on SystemExit; take the code instead. */
            PyObject *exc = PyErr_GetRaisedException();
            rc = exit_code_of(exc);
            Py_DECREF(exc);
        } else {
            PyErr_Print();   /* stderr: the console in script mode */
            rc = 1;
        }
    }
    g_interp = NULL;
    if (Py_FinalizeEx() < 0)
        rsl_log("Py_FinalizeEx reported an error");
    return rc;
}

/* Shut SDL down on the thread that initialised it (Ren'Py's): from the main
 * thread SDL_Quit() hung forever after the game quit (hardware runs 5-6).
 * Each subsystem is logged so a remaining hang names its culprit. */
static void quit_sdl(void)
{
    static const struct { Uint32 flag; const char *name; } subs[] = {
        { SDL_INIT_AUDIO, "audio" }, { SDL_INIT_GAMECONTROLLER, "gamecontroller" },
        { SDL_INIT_JOYSTICK, "joystick" }, { SDL_INIT_HAPTIC, "haptic" },
        { SDL_INIT_SENSOR, "sensor" }, { SDL_INIT_VIDEO, "video" },
        { SDL_INIT_TIMER, "timer" }, { SDL_INIT_EVENTS, "events" },
    };
    /* Ren'Py's set_timer starts SDL's timer thread through SDL_AddTimer, which
     * does not count the timer subsystem as initialised, so SDL_Quit() left the
     * thread running into the loader; it crashed there (hardware run 9). Taking
     * a reference makes the loop below quit the timer, which joins the thread. */
    SDL_InitSubSystem(SDL_INIT_TIMER);
    Uint32 init = SDL_WasInit(SDL_INIT_EVERYTHING);
    rsl_log("SDL shutdown: subsystems 0x%x", (unsigned)init);
    for (size_t i = 0; i < sizeof subs / sizeof subs[0]; i++)
        if (init & subs[i].flag) {
            rsl_log("SDL shutdown: %s", subs[i].name);
            SDL_QuitSubSystem(subs[i].flag);
        }
    SDL_Quit();
    rsl_log("SDL shutdown: done");
}

/* Every .nro started from the homebrew loader shares this process. A thread
 * that exits keeps its stack mapped, and the heap pages behind it borrowed,
 * until someone closes it, and the next allocation that reaches those pages
 * faults (hardware runs 10-11: sphaira after Exit, memset in a relaunched
 * game). CPython detaches every thread it starts, but this libnx has no
 * pthread_detach (ENOSYS); some threads are never joined at all. So every
 * pthread is tracked (create/join are wrapped, see the Makefile): detached
 * ones are closed once they exit, and at runtime exit every exited thread is
 * closed, with the entry point of those nobody joined logged. */
struct __pthread_t { Thread thr; void *rc; };   /* libnx's own layout */
void __libnx_free(void *p);
int __real___syscall_thread_create(struct __pthread_t **thread, void *(*func)(void *), void *arg,
                                   void *stack_addr, size_t stack_size);
void *__real___syscall_thread_join(struct __pthread_t *thread);
extern char _start[];   /* module start: entry offsets match the ELF */

static Mutex threads_lock;
static struct { struct __pthread_t *t; void *(*func)(void *); bool detached; } threads[256];
static size_t threads_n, threads_closed, threads_untracked;

/* Caller holds threads_lock. Closes exited threads that are detached, or all
 * exited ones at exit; returns how many tracked threads still run. */
static size_t reap_threads(bool at_exit)
{
    size_t n = 0, running = 0;
    for (size_t i = 0; i < threads_n; i++) {
        struct __pthread_t *t = threads[i].t;
        bool exited = R_SUCCEEDED(svcWaitSynchronizationSingle(t->thr.handle, 0));
        if (exited && (threads[i].detached || at_exit)) {
            if (!threads[i].detached)
                rsl_log("thread never joined, closed: entry +0x%lx",
                        (unsigned long)((char *)threads[i].func - _start));
            threadClose(&t->thr);
            __libnx_free(t);
            threads_closed++;
            continue;
        }
        if (!exited) {
            running++;
            if (at_exit)
                rsl_log("thread still running at exit: entry +0x%lx",
                        (unsigned long)((char *)threads[i].func - _start));
        }
        threads[n++] = threads[i];
    }
    threads_n = n;
    return running;
}

int __wrap___syscall_thread_create(struct __pthread_t **thread, void *(*func)(void *), void *arg,
                                   void *stack_addr, size_t stack_size)
{
    int rc = __real___syscall_thread_create(thread, func, arg, stack_addr, stack_size);
    if (rc == 0) {
        mutexLock(&threads_lock);
        reap_threads(false);
        if (threads_n < sizeof threads / sizeof threads[0]) {
            threads[threads_n].t = *thread;
            threads[threads_n].func = func;
            threads[threads_n++].detached = false;
        } else {
            threads_untracked++;   /* full: this one leaks as before */
        }
        mutexUnlock(&threads_lock);
    }
    return rc;
}

void *__wrap___syscall_thread_join(struct __pthread_t *t)
{
    mutexLock(&threads_lock);   /* joining closes it: stop tracking */
    for (size_t i = 0; i < threads_n; i++)
        if (threads[i].t == t) {
            threads[i] = threads[--threads_n];
            break;
        }
    mutexUnlock(&threads_lock);
    return __real___syscall_thread_join(t);
}

int __syscall_thread_detach(struct __pthread_t *t)
{
    int rc = ESRCH;
    mutexLock(&threads_lock);
    for (size_t i = 0; i < threads_n; i++)
        if (threads[i].t == t) {
            threads[i].detached = true;
            rc = 0;
        }
    reap_threads(false);
    mutexUnlock(&threads_lock);
    return rc;
}

static void close_threads(void)
{
    mutexLock(&threads_lock);
    size_t running = reap_threads(true);
    mutexUnlock(&threads_lock);
    rsl_log("threads: %zu closed, %zu still running, %zu untracked", threads_closed, running,
            threads_untracked);
}

static void *python_thread(void *arg)
{
    struct job *j = arg;
    j->rc = run_python(j);
    if (j->renpy)
        quit_sdl();
    j->done = true;
    return NULL;
}

static bool start_python(struct job *j, pthread_t *th)
{
    pthread_attr_t attr;
    pthread_attr_init(&attr);
    pthread_attr_setstacksize(&attr, PY_STACK);
    bool ok = pthread_create(th, &attr, python_thread, j) == 0;
    pthread_attr_destroy(&attr);
    if (!ok)
        rsl_log("could not start the Python thread");
    return ok;
}

/* Last line of a text file (progress display). */
static void last_line(const char *path, char *out, size_t len)
{
    char buf[256];
    out[0] = '\0';
    FILE *f = fopen(path, "rb");
    if (!f)
        return;
    fseek(f, 0, SEEK_END);
    long size = ftell(f);
    fseek(f, size > (long)sizeof buf - 1 ? size - (long)(sizeof buf - 1) : 0, SEEK_SET);
    size_t n = fread(buf, 1, sizeof buf - 1, f);
    fclose(f);
    buf[n] = '\0';
    while (n > 0 && (buf[n - 1] == '\n' || buf[n - 1] == '\r'))
        buf[--n] = '\0';
    char *nl = strrchr(buf, '\n');
    snprintf(out, len, "%.70s", nl ? nl + 1 : buf);
}

/* Wait for the Python thread on the main thread. At each time in dump_at
 * (seconds) while it is still running, write every Python thread's stack to
 * runtime.log, so a stall shows where it is stuck. In script mode also
 * service applet messages and show progress (the only thread that touches the
 * console: the libnx console is not thread-safe). */
/* Heat telemetry: SoC and board temperature, how busy this core is, and the
 * battery level, logged every TELEMETRY_S seconds of play. Measures whether
 * an optimisation actually lowers temperature (user report: "it gets warm"). */
#define TELEMETRY_S 30

static float read_temp(TsDeviceCode code, TsLocation legacy)
{
    TsSession s;
    float t = -1.0f;
    if (R_SUCCEEDED(tsOpenSession(&s, code))) {
        if (R_FAILED(tsSessionGetTemperature(&s, &t)))
            t = -1.0f;
        tsSessionClose(&s);
    } else {
        s32 mc;
        if (R_SUCCEEDED(tsGetTemperatureMilliC(legacy, &mc)))
            t = mc / 1000.0f;
    }
    return t;
}

static void log_telemetry(int secs, u64 *last_idle, u64 *last_tick)
{
    u64 idle = 0, tick = armGetSystemTick();
    svcGetInfo(&idle, InfoType_IdleTickCount, INVALID_HANDLE, (u64)svcGetCurrentProcessorNumber());
    int busy = -1;
    if (*last_tick && tick > *last_tick)
        busy = 100 - (int)(100 * (idle - *last_idle) / (tick - *last_tick));
    *last_idle = idle;
    *last_tick = tick;
    u32 battery = 0;
    PsmChargerType charger = PsmChargerType_Unconnected;
    psmGetBatteryChargePercentage(&battery);
    psmGetChargerType(&charger);
    rsl_log("telemetry %4d s: SoC %.1f C, board %.1f C, core %d busy %d%%, battery %u%%%s, %s",
            secs, read_temp(TsDeviceCode_LocationExternal, TsLocation_External),
            read_temp(TsDeviceCode_LocationInternal, TsLocation_Internal),
            (int)svcGetCurrentProcessorNumber(), busy, (unsigned)battery,
            charger != PsmChargerType_Unconnected ? " (charging)" : "",
            appletGetOperationMode() == AppletOperationMode_Console ? "docked" : "handheld");
}

static void watch_python(struct job *j, const int *dump_at, int n_dumps, const char *progress_file)
{
    uint64_t start = armGetSystemTick();
    int next = 0, next_telemetry = 0;
    u64 last_idle = 0, last_tick = 0;
    char line[80];
    while (!j->done) {
        if (progress_file && !appletMainLoop())
            break;
        svcSleepThread(100000000ULL);
        int secs = (int)(armTicksToNs(armGetSystemTick() - start) / 1000000000ULL);
        if (next < n_dumps && secs >= dump_at[next]) {
            next++;
            PyInterpreterState *interp = g_interp;
            int fd = rsl_log_fd();
            if (interp && fd >= 0) {
                rsl_log("watchdog: Python still running after %d s; thread stacks follow", secs);
                fd = rsl_log_fd();
                const char *err = _Py_DumpTracebackThreads(fd, interp, NULL);
                if (err)
                    rsl_log("watchdog: %s", err);
                fsync(fd);
            }
        }
        if (!progress_file && secs >= next_telemetry) {
            log_telemetry(secs, &last_idle, &last_tick);
            next_telemetry += TELEMETRY_S;
        }
        if (progress_file) {
            last_line(progress_file, line, sizeof line);
            printf("\x1b[4;1H\x1b[2K%3d s  %s", secs, line);
            consoleUpdate(NULL);
        }
    }
}

static void print_tail(const char *path, int lines)
{
    static char buf[4096];
    FILE *f = fopen(path, "rb");
    if (!f) {
        printf("(no %s)\n", path);
        return;
    }
    fseek(f, 0, SEEK_END);
    long size = ftell(f);
    fseek(f, size > (long)sizeof buf - 1 ? size - (long)(sizeof buf - 1) : 0, SEEK_SET);
    size_t n = fread(buf, 1, sizeof buf - 1, f);
    fclose(f);
    buf[n] = '\0';
    char *p = buf + n;
    for (int seen = 0; p > buf; p--)
        if (p[-1] == '\n' && ++seen > lines)
            break;
    printf("%s\n", p);
}

static void wait_for_plus(void)
{
    PadState pad;
    padConfigureInput(1, HidNpadStyleSet_NpadStandard);
    padInitializeDefault(&pad);
    while (appletMainLoop()) {
        padUpdate(&pad);
        if (padGetButtonsDown(&pad) & HidNpadButton_Plus)
            break;
        consoleUpdate(NULL);
    }
}

/* "sdmc:/.../games/foo/" -> "foo" */
static void folder_name(const char *path, char *out, size_t len)
{
    char tmp[512];
    snprintf(tmp, sizeof tmp, "%s", path);
    size_t n = strlen(tmp);
    while (n > 1 && tmp[n - 1] == '/')
        tmp[--n] = '\0';
    const char *slash = strrchr(tmp, '/');
    snprintf(out, len, "%s", slash ? slash + 1 : tmp);
}

static int run_game(struct job *job, const char *game, const char *savedir_arg, const char *ret)
{
    static char logdir[512], savedir[512], basedir[512], id[128];
    pthread_t th;

    /* Ren'Py owns the display (SDL); no text console unless it fails. */
    snprintf(basedir, sizeof basedir, "%s", game);
    folder_name(basedir, id, sizeof id);
    snprintf(logdir, sizeof logdir, ROOT "/logs/%s", id);
    if (savedir_arg)
        snprintf(savedir, sizeof savedir, "%s", savedir_arg);
    else
        snprintf(savedir, sizeof savedir, ROOT "/saves/%s", id);
    if (!rsl_mkdirs(logdir) || !rsl_mkdirs(savedir))
        rsl_log("cannot create %s or %s (SD card full or read-only?)", logdir, savedir);
    setenv("RSL_LOGDIR", logdir, 1);
    static char pylog[600];
    snprintf(pylog, sizeof pylog, "%s/python.txt", logdir);
    setenv("RSL_PYLOG", pylog, 1);   /* Python stdout/stderr, incl. tracebacks */
    setenv("RENPY_PLATFORM", "switch-aarch64", 1);
    /* "~" must exist: Ren'Py keeps save-security keys and shared
     * persistent data under ~/.renpy. Unset, it became a literal "~" folder
     * next to the runtime (hardware run 5). */
    rsl_mkdirs(ROOT "/home");
    setenv("HOME", ROOT "/home", 1);
    /* Ren'Py's developer safety net copies .rpy files to ~/.renpy/backups
     * whenever it compiles one; pointless on a console and 1.3 s per launch. */
    setenv("RENPY_DISABLE_BACKUPS", "I take responsibility for this.", 1);
    setenv("RENPY_RENDERER", "gles2", 1);
    /* Opt-in 30 fps cap (swap every 2nd vblank; Ren'Py's own switch) to
     * compare heat. ponytail: flag file until the loader has a runtime
     * settings screen (Milestone 7). */
    struct stat fst;
    if (stat(ROOT "/config/power-saver", &fst) == 0) {
        setenv("RENPY_GL_VSYNC", "2", 1);
        rsl_log("power saver: 30 fps cap");
    }
    tsInitialize();
    psmInitialize();
    load_controls(id);
    u64 total_mem = 0;
    svcGetInfo(&total_mem, InfoType_TotalMemorySize, CUR_PROCESS_HANDLE, 0);
    rsl_log("runtime start: game %s, saves %s, applet type %d, memory %llu MiB", basedir, savedir,
            (int)appletGetAppletType(), (unsigned long long)(total_mem >> 20));

    job->script = RENPY_BASE "/switch_main.py";
    job->renpy = true;
    job->argc = 5;
    job->argv[0] = RENPY_BASE "/renpy.py";
    job->argv[1] = basedir;
    job->argv[2] = "run";
    job->argv[3] = "--savedir";
    job->argv[4] = savedir;
    if (start_python(job, &th)) {
        /* SDL services applet messages; the main thread only logs telemetry.
         * No stack dumps here: reading a running Ren'Py's frames from another
         * thread crashed the console (hardware run 7). */
        watch_python(job, NULL, 0, NULL);
        pthread_join(th, NULL);
    }
    rsl_log("Ren'Py finished with status %d", job->rc);
    tsExit();
    psmExit();
    close_threads();
    rsl_heap_audit("runtime exit");

    if (job->rc != 0) {
        consoleInit(NULL);
        printf("Ren'Py stopped with status %d.\n\nDetails are in:\n", job->rc);
        printf("  %s/python.txt\n  %s/log.txt\n  %s/traceback.txt\n  " ROOT "/logs/runtime.log\n\n",
               logdir, logdir, logdir);
        printf("Press + to %s.\n", ret ? "return to the library" : "exit");
        wait_for_plus();
        consoleExit(NULL);
    }
    return job->rc;
}

static int run_script(struct job *job, const char *script)
{
    pthread_t th;
    consoleInit(NULL);
    rsl_mkdirs(ROOT "/cache");
    /* Python output goes to a file; only this thread draws the console. */
    setenv("RSL_PYLOG", ROOT "/cache/python.txt", 1);
    remove(ROOT "/cache/python-selftest.txt");
    rsl_log("runtime start: script %s, applet type %d", script, (int)appletGetAppletType());
    printf("Ren'Py Switch runtime: %s\n\nRunning (progress below; full report in " ROOT "/cache):\n", script);
    consoleUpdate(NULL);
    job->script = script;
    job->argc = 2;
    job->argv[0] = (char *)script;
    job->argv[1] = ROOT "/cache";
    if (start_python(job, &th)) {
        static const int dumps[] = { 20, 60, 120 };
        watch_python(job, dumps, 3, ROOT "/cache/python-selftest.txt");
        pthread_join(th, NULL);
    }
    rsl_log("script finished with status %d", job->rc);
    close_threads();
    printf("\n\n");
    print_tail(ROOT "/cache/python-selftest.txt", 14);
    printf("\nFinished with status %d. Press + to exit.\n", job->rc);
    wait_for_plus();
    consoleExit(NULL);
    return job->rc;
}

int main(int argc, char **argv)
{
    const char *ret = NULL, *game = NULL, *savedir = NULL, *script = SELFTEST;
    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "--return") == 0 && i + 1 < argc)
            ret = argv[++i];
        else if (strcmp(argv[i], "--game") == 0 && i + 1 < argc)
            game = argv[++i];
        else if (strcmp(argv[i], "--savedir") == 0 && i + 1 < argc)
            savedir = argv[++i];
        else
            script = argv[i];
    }

    rsl_mkdirs(ROOT "/logs");
    rsl_log_open(ROOT "/logs/runtime.log");
    Result rr = romfsInit();
    if (R_FAILED(rr))
        rsl_log("romfsInit failed: 0x%x", (unsigned)rr);
    if (PyImport_AppendInittab("_rslnx", PyInit__rslnx) < 0 || rsl_init_librenpy() < 0)
        rsl_log("could not register built-in modules");
    AppletHookCookie hook;
    appletHook(&hook, on_applet, NULL);

    struct job job = { .rc = -1 };
    int rc = game ? run_game(&job, game, savedir, ret) : run_script(&job, script);

    if (ret && envHasNextLoad()) {
        Result r = envSetNextLoad(ret, ret);
        rsl_log("return to %s: 0x%x", ret, (unsigned)r);
    }
    appletUnhook(&hook);
    romfsExit();
    rsl_log_close();
    return rc == 0 ? 0 : 1;
}

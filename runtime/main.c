/* Ren'Py Switch runtime: the process that hosts CPython and the Ren'Py engine.
 *
 * The loader chain-loads this .nro per game, so every game gets a fresh
 * process (Mesa/nouveau cannot be re-initialised inside one process).
 *
 * usage:
 *   renpy-runtime.nro [--return LOADER] --game BASEDIR [--savedir DIR]
 *       Run the Ren'Py game in BASEDIR (the folder containing game/).
 *       Saves default to <root>/saves/<id>, logs go to <root>/logs/<id>,
 *       where <id> is BASEDIR's folder name.
 *   renpy-runtime.nro [--return LOADER] [SCRIPT.py]
 *       Run a Python script on the text console (default: the self-test).
 *   --return  chain-load LOADER when finished (set by the loader).
 *
 * The other files: rslnx.c (the _rslnx module for the Python bridge), pyrun.c
 * (CPython), threads.c (thread tracking); runtime.h declares what they share. */

#include "runtime.h"   /* first: it includes Python.h */

